"""
Tipo None

O tipo de dado None em python representa o tipo sem tipo, ou poderia ser conhecido
também como tipo vazio, porém, falar que é um tipo sem tipo é mais apropriado

- O tipo None SEMPRE será especificado com a primeira letra maíuscula
- Ele sempre vai ser considerado como FALSE.

Certo: None
Errado: none

Quando utilizamos?

Nós utilizamos quando queremos criar uma variável e inicializa-lá com um tipo
sem tipo, antes de recebemos um valor final.
"""
